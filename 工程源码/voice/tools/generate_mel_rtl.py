"""Generate fixed coefficient cases from the exact integer frontend definition."""
from pathlib import Path
from kws_common import COEFF, MEL_WEIGHTS

root=Path(__file__).resolve().parents[1]
p=root.parent/'aca420/rtl/kws_goertzel.v'
coeff='\n'.join(f"   6'd{i}: coefficient=32'sd{v};" if v>=0 else
                 f"   6'd{i}: coefficient=-32'sd{-v};" for i,v in enumerate(COEFF))
mel='\n'.join(f"   10'd{b*64+k}: mel_weight=9'd{v};"
               for b,row in enumerate(MEL_WEIGHTS) for k,v in enumerate(row) if v)
ports=',\n'.join(f' output reg [31:0] power{i}' for i in range(16))
commit='\n'.join(f'     power{i}<=clamp_power(energy[{i}]);energy[{i}]<=0;' for i in range(16))
source='''// Generated by voice/tools/generate_mel_rtl.py. 63 DFT bins -> 16 Q8 Mel bands.
// One shared 32x32 multiplier; byte-packed states use one 9K BRAM.
// Serial state access trades otherwise idle sample clocks for memory capacity.
module kws_goertzel(input wire clk,rst,sample_valid,
 input wire signed [15:0] sample_in,
 output reg sample_overrun,result_valid,result_overflow,
@PORTS@);
 localparam IDLE=0,READ=1,FEEDBACK_MUL=2,FEEDBACK_SAVE=3,
  POWER_MUL=4,POWER_SQ1=5,POWER_SQ2=6,POWER_COEFF=7,POWER_SAVE=8,
  MEL_MUL=9,MEL_SAVE=10,COMMIT=11,READ_POWER=12,
  RAM_WAIT=13,RAM_LOAD=14,RAM_STORE=15;
 reg [3:0] state;
 reg [5:0] band;reg [3:0] mel_band;reg [6:0] count;
 // 63 bins x (s1,s2) x four bytes: preserve all 31 signed state bits.
 // Wide shallow memories previously consumed eight 9K blocks on EG4S20.
 (* ram_style="bram" *) reg [7:0] packed_states[0:511];
 reg [8:0] ram_addr;reg [2:0] byte_index;reg reading_power;
 reg [7:0] ram_q;
 reg signed [30:0] q1,q2;
 reg signed [30:0] next_s1,next_s2;
 wire [31:0] store_word=byte_index[2]?{1'b0,next_s2}:{1'b0,next_s1};
 wire [7:0] store_byte=store_word>>(byte_index[1:0]*8);
 // No reset on RAM or its read register, preserving ERAM inference.
 always @(posedge clk)begin
  ram_q<=packed_states[ram_addr];
  if(state==RAM_STORE)packed_states[{band,byte_index}]<=store_byte;
 end
 reg signed [31:0] sample_reg,mul_a,mul_b;
 wire signed [63:0] product=mul_a*mul_b;
 reg signed [63:0] square1,square2;
 reg [31:0] mel_power;
 reg [47:0] energy[0:15];
 reg overflow;
 wire signed [63:0] recurrence=$signed(sample_reg)+(product>>>16)-$signed(q2);
 wire rec_overflow=recurrence>64'sd1073741823 || recurrence< -64'sd1073741824;
 wire signed [30:0] limited=recurrence>64'sd1073741823 ? 31'sh3fffffff :
  recurrence< -64'sd1073741824 ? 31'sh40000000 : recurrence[30:0];
 wire signed [64:0] raw_power={square1[63],square1}+{square2[63],square2}-{product[63],product};
 wire signed [64:0] scaled=raw_power>>>17;
 wire [31:0] bin_power=raw_power<0 ? 32'd0 : scaled>65'sd4294967295 ? 32'hffffffff : scaled[31:0];
 function signed [31:0] coefficient;
  input [5:0] index;
  begin case(index)
@COEFF@
   default:coefficient=0;
  endcase end
 endfunction
 function [8:0] mel_weight;
  input [9:0] address;
  begin case(address)
@MEL@
   default:mel_weight=0;
  endcase end
 endfunction
 function [31:0] clamp_power;
  input [47:0] value;
  begin clamp_power=(value>>7)>48'hffffffff ? 32'hffffffff : (value>>7);end
 endfunction
 integer i;
 always @(posedge clk)begin
  if(rst)begin
   state<=IDLE;band<=0;mel_band<=0;count<=0;sample_reg<=0;
   ram_addr<=0;byte_index<=0;reading_power<=0;q1<=0;q2<=0;next_s1<=0;next_s2<=0;
   mul_a<=0;mul_b<=0;square1<=0;square2<=0;mel_power<=0;
   overflow<=0;sample_overrun<=0;result_overflow<=0;result_valid<=0;
   for(i=0;i<16;i=i+1)energy[i]<=0;
  end else begin
   result_valid<=0;
   if(sample_valid && state!=IDLE)sample_overrun<=1;
   case(state)
    IDLE:if(sample_valid)begin sample_reg<=sample_in;band<=0;state<=READ;end
    READ:begin
     reading_power<=0;byte_index<=0;ram_addr<={band,3'd0};
     // First frame sample overwrites all words; stale/reset contents are ignored.
     state<=count==0 ? FEEDBACK_MUL : RAM_WAIT;
    end
    RAM_WAIT:state<=RAM_LOAD;
    RAM_LOAD:begin
     case(byte_index)
      0:q1[7:0]<=ram_q;
      1:q1[15:8]<=ram_q;
      2:q1[23:16]<=ram_q;
      3:q1[30:24]<=ram_q[6:0];
      4:q2[7:0]<=ram_q;
      5:q2[15:8]<=ram_q;
      6:q2[23:16]<=ram_q;
      7:q2[30:24]<=ram_q[6:0];
     endcase
     if(byte_index==7)state<=reading_power ? POWER_MUL : FEEDBACK_MUL;
     else begin byte_index<=byte_index+1'b1;ram_addr<=ram_addr+1'b1;state<=RAM_WAIT;end
    end
    FEEDBACK_MUL:begin
     mul_a<=count==0 ? 0 : $signed(q1);mul_b<=coefficient(band);state<=FEEDBACK_SAVE;
    end
    FEEDBACK_SAVE:begin
     // The first sample overwrites each RAM word; uninitialized state is never used.
     next_s2<=count==0 ? 0 : q1;
     next_s1<=count==0 ? sample_reg[30:0] : limited;
     if(count!=0 && rec_overflow)overflow<=1;
     byte_index<=0;state<=RAM_STORE;
    end
    RAM_STORE:begin
     if(byte_index!=7)byte_index<=byte_index+1'b1;
     else begin
     if(band!=62)begin band<=band+1'b1;state<=READ;end
     else if(count==127)begin band<=0;state<=READ_POWER;end
     else begin count<=count+1'b1;state<=IDLE;end
     end
    end
    READ_POWER:begin reading_power<=1;byte_index<=0;ram_addr<={band,3'd0};state<=RAM_WAIT;end
    POWER_MUL:begin mul_a<=q1;mul_b<=q1;state<=POWER_SQ1;end
    POWER_SQ1:begin square1<=product;mul_a<=q2;mul_b<=q2;state<=POWER_SQ2;end
    POWER_SQ2:begin square2<=product;mul_a<=q1;mul_b<=coefficient(band);state<=POWER_COEFF;end
    POWER_COEFF:begin mul_a<=product>>>16;mul_b<=q2;state<=POWER_SAVE;end
    POWER_SAVE:begin mel_power<=bin_power;mel_band<=0;state<=MEL_MUL;end
    MEL_MUL:begin mul_a<=$signed({1'b0,mel_power[31:1]});
     mul_b<=$signed({23'd0,mel_weight({mel_band,band})});state<=MEL_SAVE;end
    MEL_SAVE:begin
     energy[mel_band]<=energy[mel_band]+product[47:0];
     if(mel_band!=15)begin mel_band<=mel_band+1'b1;state<=MEL_MUL;end
     else if(band==62)state<=COMMIT;
     else begin band<=band+1'b1;state<=READ_POWER;end
    end
    COMMIT:begin
@COMMIT@
     result_valid<=1;result_overflow<=overflow;overflow<=0;count<=0;state<=IDLE;
    end
    default:state<=IDLE;
   endcase
  end
 end
endmodule
'''
for key,value in [('PORTS',ports),('COEFF',coeff),('MEL',mel),('COMMIT',commit)]:
    source=source.replace('@'+key+'@',value)
p.write_text(source)
print('Generated',p)
