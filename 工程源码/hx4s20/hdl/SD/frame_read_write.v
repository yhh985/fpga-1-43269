`timescale 1ns/1ps
module frame_read_write
#
(
	parameter MEM_DATA_BITS          = 32,
	parameter READ_DATA_BITS         = 32,
	parameter WRITE_DATA_BITS        = 32,
	parameter ADDR_BITS              = 21,
	parameter BURST_BITS             = 9,//
	// 2026-10-05: 原为 256。frame_fifo_read/frame_fifo_write 的默认值与全部回归
	// 用例都是 128，256 从未被验证；仿真证明 256 下第 2 帧起 FIFO 与 SDRAM 写入
	// 失配（tb_frame_store_backpressure 在 256 报 fatal，128 全过）。恢复为 128。
	parameter BURST_SIZE             = 128,
	parameter WRITE_V_FLIP           = 1,      // 1: vertical flip when writing TF/BMP frame into SDRAM
	parameter FRAME_WIDTH            = 640,
	parameter FRAME_HEIGHT           = 480
) 
(
	input                            rst,                  
	input                            write_rst,             // reset for the write_clk domain (synchronized at the source)
	input                            mem_clk,                    // external memory controller user interface clock
	input							 Sdr_init_done,
	input							 Sdr_init_ref_vld,
    input							 Sdr_busy,
	
    /*
    output                           rd_burst_req,               // to external memory controller,send out a burst read request
	output[BURST_BITS - 1:0]         rd_burst_len,               // to external memory controller,data length of the burst read request, not bytes
	output[ADDR_BITS - 1:0]          rd_burst_addr,              // to external memory controller,base address of the burst read request 
	input                            rd_burst_data_valid,        // from external memory controller,read data valid 
	input[MEM_DATA_BITS - 1:0]       rd_burst_data,              // from external memory controller,read request data
	input                            rd_burst_finish,            // from external memory controller,burst read finish
	*/
	output							 App_rd_en,
	output[ADDR_BITS - 1:0]			 App_rd_addr,
	input							 Sdr_rd_en,					 //read_data_valid
	input[MEM_DATA_BITS - 1:0]		 Sdr_rd_dout,
	
	input                            read_clk,                   // data read module clock
	input                            read_req,                   // data read module read request,keep '1' until read_req_ack = '1'
	output                           read_req_ack,               // data read module read request response
	output                           read_buffer_toggle,         // mem_clk-domain final reader-buffer selection
	output [1:0]                     read_buffer_index,
	output                           read_finish,                // data read module read request finish
	input[ADDR_BITS - 1:0]           read_addr_0,                // data read module read request base address 0, used when read_addr_index = 0
	input[ADDR_BITS - 1:0]           read_addr_1,                // data read module read request base address 1, used when read_addr_index = 1
	input[ADDR_BITS - 1:0]           read_addr_2,                // data read module read request base address 1, used when read_addr_index = 2
	input[ADDR_BITS - 1:0]           read_addr_3,                // data read module read request base address 1, used when read_addr_index = 3
	input[1:0]                       read_addr_index,            // select valid base address from read_addr_0 read_addr_1 read_addr_2 read_addr_3
	input[ADDR_BITS - 1:0]           read_len,                   // data read module read request data length
	input                            read_en,                    // data read module read request for one data, read_data valid next clock
	output[READ_DATA_BITS  - 1:0]    read_data,                  // read data
	/*
	output                           wr_burst_req,               // to external memory controller,send out a burst write request
	output[BURST_BITS - 1:0]         wr_burst_len,               // to external memory controller,data length of the burst write request, not bytes
	output[ADDR_BITS - 1:0]          wr_burst_addr,              // to external memory controller,base address of the burst write request 
	input                            wr_burst_data_req,          // from external memory controller,write data request ,before data 1 clock
	output[MEM_DATA_BITS - 1:0]      wr_burst_data,              // to external memory controller,write data
	input                            wr_burst_finish,            // from external memory controller,burst write finish
	*/
	output							 App_wr_en,
	output[ADDR_BITS - 1:0]			 App_wr_addr,
	output[MEM_DATA_BITS - 1:0]	 App_wr_din,
	output[3:0]						 App_wr_dm,
	
	//
	input                            write_clk,                  // data write module clock
	input                            write_req,                  // data write module write request,keep '1' until read_req_ack = '1'
	output                           write_req_ack,              // data write module write request response
	output                           write_finish,               // data write module write request finish
	input[ADDR_BITS - 1:0]           write_addr_0,               // data write module write request base address 0, used when write_addr_index = 0
	input[ADDR_BITS - 1:0]           write_addr_1,               // data write module write request base address 1, used when write_addr_index = 1
	input[ADDR_BITS - 1:0]           write_addr_2,               // data write module write request base address 1, used when write_addr_index = 2
	input[ADDR_BITS - 1:0]           write_addr_3,               // data write module write request base address 1, used when write_addr_index = 3
	input[1:0]                       write_addr_index,           // select valid base address from write_addr_0 write_addr_1 write_addr_2 write_addr_3
	input[ADDR_BITS - 1:0]           write_len,                  // data write module write request data length
	output                           write_data_ready,           // write_clk-domain valid/data acceptance
	input                            write_en,                   // data write module write request for one data
	input[WRITE_DATA_BITS - 1:0]     write_data                 // write data

);
wire[BURST_BITS - 1:0]                           wrusedw;                    // write used words
wire[BURST_BITS - 1:0]                           rdusedw;                    // read used words

wire 								 App_rd_busy;
wire								 App_wr_busy;

wire                                 read_fifo_aclr;             // fifo Asynchronous clear
wire                                 write_fifo_aclr;            // fifo Asynchronous clear
// rst is generated in the memory clock domain. Assertion may cross domains
// asynchronously, but release must be synchronized to write_clk before it is
// used by the native asynchronous FIFO or its ready pipeline.
(* async_reg = "true", syn_preserve = 1 *) reg [2:0] write_rst_release;
wire                                 write_domain_rst = write_rst_release[2];
reg [1:0]                            write_fifo_aclr_sync;
wire                                 write_fifo_async_reset = write_domain_rst || write_fifo_aclr_sync[1];
reg [1:0]                            write_fifo_reset_release;
wire                                 write_fifo_reset = write_fifo_reset_release[1];
wire                                 write_fifo_full;
reg [2:0]                            write_fifo_release;

wire O_wr_busy;
wire O_rd_busy;
wire O_rd_urgent;

assign App_wr_busy = O_wr_busy;//下个时钟写指令拉高
// Let the display refill at burst boundaries when its FIFO is below half
// full. An active write stays uninterrupted; the next write waits instead
// of starving video while a fast BMP source fills the write FIFO.
assign App_rd_busy = O_rd_busy || O_rd_urgent;
assign App_wr_dm = 4'b0000;

// Local reset release for the write-clock side of frame storage. Sample the
// memory-domain reset as data so neither its assertion nor deassertion drives
// an asynchronous reset pin in the SD clock domain; all release transitions
// are consequently generated by write_clk.
always @(posedge write_clk) begin
    if (write_rst)
        write_rst_release <= 3'b111;
    else
        write_rst_release <= {write_rst_release[1:0], 1'b0};
end

// frame_fifo_write raises fifo_aclr in mem_clk. Synchronize that clear
// request before using it as the asynchronous assertion for the write-side
// FIFO reset release; its deassertion is then local to write_clk as well.
always @(posedge write_clk or posedge write_domain_rst) begin
    if (write_domain_rst)
        write_fifo_aclr_sync <= 2'b00;
    else
        write_fifo_aclr_sync <= {write_fifo_aclr_sync[0], write_fifo_aclr};
end

always @(posedge write_clk or posedge write_fifo_async_reset) begin
    if (write_fifo_async_reset)
        write_fifo_reset_release <= 2'b11;
    else
        write_fifo_reset_release <= {write_fifo_reset_release[0], 1'b0};
end

// The generated FIFO releases its own write-side reset after two clocks.
// Hold ready low for a third write clock so no accepted pixel is lost during
// reset release. full_flag is computed from the local write pointer and the
// synchronized read pointer: delayed reads make this safely conservative.
always @(posedge write_clk or posedge write_fifo_reset) begin
    if (write_fifo_reset) write_fifo_release <= 3'b000;
    else write_fifo_release <= {write_fifo_release[1:0], 1'b1};
end
// Asynchronous assertion already clears release immediately. The permission
// itself uses only write-clock registers; raw mem-clock reset deassertion
// must not propagate through ready into the scaler's pixel enables.
assign write_data_ready = write_fifo_release[2] && !write_fifo_full;

//instantiate an asynchronous FIFO 
wfifo_32_32_512 write_buf
	(
	.clkr                      	(mem_clk                  ),          // Read side clock
	.clkw                      	(write_clk                ),          // Write side clock
	.rst                       	(write_fifo_reset         ),          // Asynchronous clear
	.we                      	(write_en && write_data_ready),       // Accepted valid/data only
	.re                      	(App_wr_en        		  ),          // Read Request
	.di                       	(write_data               ),          // Input Data
	.empty_flag                 (                         ),          // Read side Empty flag
	.full_flag                  (write_fifo_full           ),          // Write side Full flag
	.wrusedw                	(              	  		  ),          // Read Used Words
	.rdusedw                	(rdusedw                  ),          // Write Used Words
	.dout                       (App_wr_din		          )
);

